from dataclasses import dataclass
import math

import numpy as np


SOLAR_CONSTANT_W_M2 = 1361.0
AU_KM = 149_597_870.7


def solar_flux_w_m2(distance_km):
    """Solar irradiance adjusted for distance from the Sun."""
    distance = np.asarray(distance_km, dtype=float)

    if not np.all(np.isfinite(distance)) or np.any(distance <= 0.0):
        raise ValueError("Sun distance must be finite and greater than zero.")

    return SOLAR_CONSTANT_W_M2 * (AU_KM / distance) ** 2


@dataclass
class PanelConfig:
    kind: str = "tracking"
    normal_elevation_deg: float = 0.0
    normal_azimuth_deg: float = 0.0
    area_m2: float = 1.0
    efficiency: float = 0.28
    dust_loss: float = 0.05
    degradation: float = 0.0
    panel_height_m: float = 2.0

    def __post_init__(self):
        if self.kind not in ("tracking", "fixed"):
            raise ValueError("Panel kind must be 'tracking' or 'fixed'.")

        numeric_values = {
            "normal_elevation_deg": self.normal_elevation_deg,
            "normal_azimuth_deg": self.normal_azimuth_deg,
            "area_m2": self.area_m2,
            "efficiency": self.efficiency,
            "dust_loss": self.dust_loss,
            "degradation": self.degradation,
            "panel_height_m": self.panel_height_m,
        }

        for name, value in numeric_values.items():
            if not math.isfinite(value):
                raise ValueError(f"{name} must be finite.")

        if not -90.0 <= self.normal_elevation_deg <= 90.0:
            raise ValueError("Panel normal elevation must be between -90 and 90 degrees.")

        if self.area_m2 <= 0.0:
            raise ValueError("Panel area must be greater than zero.")

        if not 0.0 <= self.efficiency <= 1.0:
            raise ValueError("Panel efficiency must be between 0 and 1.")

        if not 0.0 <= self.dust_loss <= 1.0:
            raise ValueError("Dust loss must be between 0 and 1.")

        if not 0.0 <= self.degradation <= 1.0:
            raise ValueError("Degradation must be between 0 and 1.")

        if self.panel_height_m < 0.0:
            raise ValueError("Panel height cannot be negative.")


def panel_cosine(azimuth_deg, elevation_deg, config):
    """Cosine of incidence angle between sunlight and panel normal."""
    azimuth = np.asarray(azimuth_deg, dtype=float)
    elevation = np.asarray(elevation_deg, dtype=float)

    if not np.all(np.isfinite(azimuth)) or not np.all(np.isfinite(elevation)):
        raise ValueError("Sun angles must be finite.")

    if np.any((elevation < -90.0) | (elevation > 90.0)):
        raise ValueError("Sun elevation must be between -90 and 90 degrees.")

    normal_azimuth = (
        azimuth if config.kind == "tracking"
        else config.normal_azimuth_deg
    )

    azimuth_difference = np.radians(azimuth - normal_azimuth)
    sun_elevation = np.radians(elevation)
    normal_elevation = math.radians(config.normal_elevation_deg)

    cosine = (
        math.sin(normal_elevation) * np.sin(sun_elevation)
        + math.cos(normal_elevation)
        * np.cos(sun_elevation)
        * np.cos(azimuth_difference)
    )

    return np.clip(cosine, 0.0, 1.0)


def solar_power_w(
    distance_km,
    azimuth_deg,
    elevation_deg,
    sun_fraction,
    config,
):
    """Calculate electrical power generated by a solar panel in watts."""
    fraction = np.asarray(sun_fraction, dtype=float)

    if not np.all(np.isfinite(fraction)) or np.any((fraction < 0.0) | (fraction > 1.0)):
        raise ValueError("Sun fraction must be finite and between 0 and 1.")

    flux = solar_flux_w_m2(distance_km)
    incidence = panel_cosine(azimuth_deg, elevation_deg, config)

    return (
        flux
        * config.area_m2
        * config.efficiency
        * (1.0 - config.dust_loss)
        * (1.0 - config.degradation)
        * incidence
        * fraction
    )
